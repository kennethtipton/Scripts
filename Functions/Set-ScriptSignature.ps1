<#
.SYNOPSIS
    Signs every PowerShell script that is unsigned or has changed since it was signed.
.DESCRIPTION
    Safe to run as often as you like. For each .ps1/.psm1/.psd1 under -Path:

      Status before          Action
      ---------------------  --------------------------------------------------------------
      NotSigned              Prepare the file (see below), then sign it
      HashMismatch           Edited after signing: sign again (the old signature block is
                             replaced)
      Valid, this cert       Skip
      Valid, other cert      Report only (sign with -Force)
      Anything else          Report only (sign with -Force)

    Preparing an unsigned file: line endings are normalized to CRLF and the file is made to
    end with a newline followed by one blank line. That trailing blank line is what made
    signing work reliably in the past, so it is added to every unsigned script before
    signing. The file's encoding (with or without BOM) is kept.

    Signatures are SHA256 and timestamped, so they stay valid after the certificate expires.
    If the timestamp server cannot be reached the file is signed without a timestamp and a
    warning is shown.
.PARAMETER Path
    Script files or folders. Defaults to C:\SCRIPTS.
.PARAMETER NoRecurse
    Only the given folders, not their subfolders.
.PARAMETER Exclude
    Folder names to skip anywhere in the tree. Defaults to Logs and Data.
.PARAMETER CertThumbprint
    Code-signing certificate in Cert:\CurrentUser\My or Cert:\LocalMachine\My.
    Defaults to the GGI code-signing certificate.
.PARAMETER TimestampServer
    RFC 3161 timestamp server. Defaults to http://timestamp.digicert.com.
.PARAMETER Force
    Also re-sign files that are validly signed by another certificate or have other statuses.
.EXAMPLE
    PS> Set-ScriptSignature -WhatIf
.EXAMPLE
    PS> Set-ScriptSignature | Format-Table -AutoSize
.EXAMPLE
    PS> Set-ScriptSignature -Path 'C:\SCRIPTS\Applications\POSHACME'
.INPUTS
    [string[]] Path, [switch] NoRecurse, [string[]] Exclude, [string] CertThumbprint, [string] TimestampServer, [switch] Force
.OUTPUTS
    [pscustomobject] one row per script: File, Before, Action, After, Timestamped
