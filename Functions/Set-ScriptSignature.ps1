function Set-ScriptSignature {
    [CmdletBinding(SupportsShouldProcess = $true)]
    [OutputType([pscustomobject])]
    param(
        [Parameter(Mandatory = $false)]
        [string[]]$Path = 'C:\SCRIPTS',

        [Parameter(Mandatory = $false)]
        [switch]$NoRecurse,

        [Parameter(Mandatory = $false)]
        [string[]]$Exclude = @('Logs', 'Data'),

        [Parameter(Mandatory = $false)]
        [string]$CertThumbprint = 'F1C24CF6B8C13B81BE0C8295D75919CB5F8E4C35',

        [Parameter(Mandatory = $false)]
        [string]$TimestampServer = 'http://timestamp.digicert.com',

        [Parameter(Mandatory = $false)]
        [switch]$Force
    )

    #region Certificate
    $Thumb = ($CertThumbprint -replace '\s', '').ToUpper()
    $Cert = Get-Item -Path "Cert:\CurrentUser\My\$Thumb" -ErrorAction SilentlyContinue
    if (-not $Cert) { $Cert = Get-Item -Path "Cert:\LocalMachine\My\$Thumb" -ErrorAction SilentlyContinue }
    if (-not $Cert) { throw "Certificate $Thumb not found in CurrentUser\My or LocalMachine\My." }
    if (-not $Cert.HasPrivateKey) { throw "Certificate $Thumb has no private key in this store." }
    if ($Cert.NotAfter -lt (Get-Date)) { throw "Certificate $Thumb expired on $($Cert.NotAfter)." }
    Write-Verbose "Signing with $($Cert.Subject) [$Thumb], expires $($Cert.NotAfter)"
    #endregion

    #region Helpers
    # Normalize to CRLF and end with a newline plus one blank line, keeping the encoding.
    function Initialize-ScriptFile {
        param([string]$FilePath)

        $Bytes = [System.IO.File]::ReadAllBytes($FilePath)

        $Encoding = $null
        $Bom = $false
        if ($Bytes.Length -ge 3 -and $Bytes[0] -eq 0xEF -and $Bytes[1] -eq 0xBB -and $Bytes[2] -eq 0xBF) {
            $Encoding = New-Object System.Text.UTF8Encoding($true); $Bom = $true; $Start = 3
        }
        elseif ($Bytes.Length -ge 2 -and $Bytes[0] -eq 0xFF -and $Bytes[1] -eq 0xFE) {
            $Encoding = New-Object System.Text.UnicodeEncoding($false, $true); $Bom = $true; $Start = 2
        }
        elseif ($Bytes.Length -ge 2 -and $Bytes[0] -eq 0xFE -and $Bytes[1] -eq 0xFF) {
            $Encoding = New-Object System.Text.UnicodeEncoding($true, $true); $Bom = $true; $Start = 2
        }
        else {
            $Start = 0
            try {
                # Strict UTF-8 (no BOM); plain ASCII also passes
                $Encoding = New-Object System.Text.UTF8Encoding($false, $true)
                [void]$Encoding.GetString($Bytes)
            }
            catch {
                # Not valid UTF-8: treat as the system ANSI code page, as Windows PowerShell does
                $Encoding = [System.Text.Encoding]::Default
            }
        }

        $Text = $Encoding.GetString($Bytes, $Start, $Bytes.Length - $Start)
        $New  = ($Text -replace "`r?`n", "`r`n").TrimEnd("`r", "`n", ' ', "`t") + "`r`n`r`n"

        if ($New -ne $Text) {
            if ($Bom) {
                [System.IO.File]::WriteAllText($FilePath, $New, $Encoding)
            }
            else {
                $OutEncoding = if ($Encoding -is [System.Text.UTF8Encoding]) { New-Object System.Text.UTF8Encoding($false) } else { $Encoding }
                [System.IO.File]::WriteAllBytes($FilePath, $OutEncoding.GetBytes($New))
            }
            return $true
        }
        return $false
    }

    function Invoke-Sign {
        param([string]$FilePath)
        $P = @{ FilePath = $FilePath; Certificate = $Cert; HashAlgorithm = 'SHA256'; ErrorAction = 'Stop' }
        if ($TimestampServer) {
            try { return @{ Sig = (Set-AuthenticodeSignature @p -TimestampServer $TimestampServer); Note = '' } }
            catch { Write-Warning "Timestamp server failed for $(Split-Path $FilePath -Leaf): $($_.Exception.Message). Signing without a timestamp." }
        }
        @{ Sig = (Set-AuthenticodeSignature @p); Note = ' (no timestamp)' }
    }
    #endregion

    #region Files
    $Extensions = '.ps1', '.psm1', '.psd1'
    $Files = foreach ($P in $Path) {
        if (Test-Path -Path $P -PathType Leaf) {
            Get-Item -Path $P
        }
        elseif (Test-Path -Path $P -PathType Container) {
            $Root = (Resolve-Path -Path $P).Path.TrimEnd('\')
            Get-ChildItem -Path $Root -File -Recurse:(-not $NoRecurse) | Where-Object {
                # Skip files inside an excluded folder name below $Root (e.g. ...\Logs\..., ...\Data\...)
                $Relative = $_.DirectoryName.Substring($Root.Length)
                $_.Extension -in $Extensions -and
                -not (@($Relative -split '\\') | Where-Object { $_ -and ($_ -in $Exclude) })
            }
        }
        else {
            Write-Warning "Not found: $P"
        }
    }
    $Files = @($Files | Sort-Object FullName -Unique)
    if ($Files.Count -eq 0) { Write-Warning 'No scripts found.'; return }
    #endregion

    #region Sign
    $Results = foreach ($File in $Files) {
        $Before = Get-AuthenticodeSignature -FilePath $File.FullName
        $Status = "$($Before.Status)"
        $Ours   = $Before.SignerCertificate -and $Before.SignerCertificate.Thumbprint -eq $Thumb

        $Row = [ordered]@{
            File        = $File.FullName
            Before      = if ($Before.SignerCertificate -and -not $Ours) { "$Status (other signer)" } else { $Status }
            Action      = ''
            After       = ''
            Timestamped = $false
        }

        $Mode = switch ($Status) {
            'NotSigned'    { 'prepare' }
            'HashMismatch' { 'sign' }
            'Valid'        { if ($Ours) { 'skip' } elseif ($Force) { 'sign' } else { 'report' } }
            default        { if ($Force) { 'sign' } else { 'report' } }
        }

        switch ($Mode) {
            'skip'   { $Row.Action = 'Skipped (signed, unchanged)'; $Row.After = $Status; $Row.Timestamped = [bool]$Before.TimeStamperCertificate }
            'report' { $Row.Action = 'Not changed (use -Force)';    $Row.After = $Status }
            default {
                if ($PSCmdlet.ShouldProcess($File.FullName, $(if ($Mode -eq 'prepare') { 'Add trailing blank line and sign' } else { 'Re-sign' }))) {
                    try {
                        $Prepared = $false
                        if ($Mode -eq 'prepare') { $Prepared = Initialize-ScriptFile -FilePath $File.FullName }
                        $R = Invoke-Sign -FilePath $File.FullName
                        $Row.Action = $(if ($Mode -eq 'prepare') { 'Signed' + $(if ($Prepared) { ' (blank line added)' } else { '' }) } else { 'Re-signed' }) + $R.Note
                        $Row.After = "$($R.Sig.Status)"
                        $Row.Timestamped = [bool]$R.Sig.TimeStamperCertificate
                    }
                    catch {
                        $Row.Action = "FAILED: $($_.Exception.Message)"
                        $Row.After = "$((Get-AuthenticodeSignature -FilePath $File.FullName).Status)"
                    }
                }
                else {
                    $Row.Action = 'Would sign (WhatIf)'
                    $Row.After = $Status
                }
            }
        }
        [pscustomobject]$Row
    }

    $Results
    $Signed  = @($Results | Where-Object { $_.Action -like 'Signed*' -or $_.Action -like 'Re-signed*' }).Count
    $Skipped = @($Results | Where-Object { $_.Action -like 'Skipped*' }).Count
    $Other   = @($Results | Where-Object { $_.Action -like 'Not changed*' }).Count
    $Failed  = @($Results | Where-Object {
        $_.Action -like 'FAILED*' -or (($_.Action -like 'Signed*' -or $_.Action -like 'Re-signed*') -and $_.After -ne 'Valid')
    }).Count
    Write-Host ("Signed {0}, skipped {1}, left alone {2}, problems {3} (of {4} scripts)" -f $Signed, $Skipped, $Other, $Failed, $Results.Count) -ForegroundColor $(if ($Failed) { 'Yellow' } else { 'Green' })
    #endregion
}

