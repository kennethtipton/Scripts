<#
.SYNOPSIS
    Sends an e-mail from any script or application, using the SMTP settings in Data\Settings\Scripts.json.
.DESCRIPTION
    One way for every application to send notifications (failures, reports, renewals). The SMTP
    server, port, TLS, sender, default recipients and subject prefix come from the Mail section of
    C:\SCRIPTS\Data\Settings\Scripts.json, with this computer's override (Scripts.<COMPUTERNAME>.json)
    applied, so a device on another network can use its own relay.

    Mail settings (Scripts.json):
      "Mail": {
        "Enabled": true,
        "SmtpServers": [ "smtp.generationsgaither.com", "srv010010050050.generationsgaither.com" ],
        "Port": 25,
        "UseSsl": false,
        "From": "PowerShell Scripts <scripts@generationsgaither.com>",
        "To": [ "it@generationsgaither.com" ],
        "SubjectPrefix": "[PSM]",
        "TimeoutSeconds": 30,
        "PickupDirectory": ""
      }

    SmtpServers are tried in order; the first that accepts the message is used. UseSsl turns on
    STARTTLS. Without a credential the message is sent anonymously, which Exchange accepts from the
    internal network for internal recipients; mail to outside addresses needs a relay connector on
    Exchange. PickupDirectory (for testing) writes the message as an .eml file there instead of
    sending it.

    The subject gets the prefix and, with -Application, the application name; the body gets a
    footer naming the application, computer and time. Every send is logged (Write-AdvancedLog).

    A failed send does not stop the caller: the result is returned (Sent = $false, with the reason)
    and a warning is written. Use -ThrowOnError when the caller must stop.
.PARAMETER Subject
    Subject line (the prefix and application name are added in front).
.PARAMETER Body
    Message text. Plain text unless -BodyAsHtml.
.PARAMETER To
    Recipients. Defaults to Mail.To in the settings.
.PARAMETER Cc
    Copy recipients.
.PARAMETER Bcc
    Blind copy recipients.
.PARAMETER From
    Sender. Defaults to Mail.From in the settings.
.PARAMETER Application
    Name of the sending application (for example DynamicGroups); shown in the subject and footer.
.PARAMETER Attachments
    Files to attach.
.PARAMETER Priority
    Normal (default), High or Low.
.PARAMETER BodyAsHtml
    The body is HTML.
.PARAMETER NoFooter
    Do not add the sender footer.
.PARAMETER ThrowOnError
    Throw when the message cannot be sent, instead of returning Sent = $false.
.PARAMETER SettingsPath
    Settings file. Defaults to C:\SCRIPTS\Data\Settings\Scripts.json (next to this Functions folder).
.PARAMETER LogFileName
    Base name of the text log in C:\SCRIPTS\Logs. Defaults to Send-ScriptMail.
.EXAMPLE
    PS> Send-ScriptMail -Subject 'Certificate renewed' -Body 'New thumbprint ...' -Application 'PoshAcmeExchangeServer'
.EXAMPLE
    PS> Send-ScriptMail -Subject 'Sync failed' -Body $Report -BodyAsHtml -Priority High -To 'kenneth@generationsgaither.com'
.EXAMPLE
    PS> $R = Send-ScriptMail -Subject 'Test' -Body 'Hello'; if (-not $R.Sent) { $R.Message }
.INPUTS
    [string] Subject, Body, From, Application, Priority, SettingsPath, LogFileName; [string[]] To, Cc, Bcc, Attachments
.OUTPUTS
    [pscustomobject] Sent, Server, To, Subject, Message
