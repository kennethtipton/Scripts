function Send-ScriptMail {
    [CmdletBinding(SupportsShouldProcess = $true)]
    [OutputType([pscustomobject])]
    param(
        [Parameter(Mandatory = $true)]
        [string]$Subject,

        [Parameter(Mandatory = $false)]
        [AllowEmptyString()]
        [string]$Body = '',

        [Parameter(Mandatory = $false)]
        [string[]]$To,

        [Parameter(Mandatory = $false)]
        [string[]]$Cc,

        [Parameter(Mandatory = $false)]
        [string[]]$Bcc,

        [Parameter(Mandatory = $false)]
        [string]$From,

        [Parameter(Mandatory = $false)]
        [string]$Application,

        [Parameter(Mandatory = $false)]
        [string[]]$Attachments,

        [Parameter(Mandatory = $false)]
        [ValidateSet('Normal', 'High', 'Low')]
        [string]$Priority = 'Normal',

        [Parameter(Mandatory = $false)]
        [switch]$BodyAsHtml,

        [Parameter(Mandatory = $false)]
        [switch]$NoFooter,

        [Parameter(Mandatory = $false)]
        [switch]$ThrowOnError,

        [Parameter(Mandatory = $false)]
        [string]$SettingsPath = (Join-Path -Path (Split-Path -Path $PSScriptRoot -Parent) -ChildPath 'Data\Settings\Scripts.json'),

        [Parameter(Mandatory = $false)]
        [string]$LogFileName = 'Send-ScriptMail'
    )

    #region Logging
    $WriteLogPath = Join-Path -Path $PSScriptRoot -ChildPath 'Write-AdvancedLog.ps1'
    if (Test-Path -Path $WriteLogPath) { . $WriteLogPath }
    function Write-MailLog {
        param([Parameter(Mandatory)][string]$Message, [ValidateSet('INFO', 'WARNING', 'ERROR')][string]$LogType = 'INFO')
        if ($LogType -eq 'INFO') { Write-Verbose $Message } else { Write-Warning $Message }
        if (-not $WhatIfPreference -and (Get-Command -Name Write-AdvancedLog -ErrorAction SilentlyContinue)) {
            try { Write-AdvancedLog -Message $Message -ScriptName 'Send-ScriptMail.ps1' -LogFileName $LogFileName -LogType $LogType } catch { }
        }
    }
    #endregion

    $Result = [ordered]@{ Sent = $false; Server = ''; To = ''; Subject = ''; Message = '' }
    function Stop-Send {
        param([string]$Why)
        $Result.Message = $Why
        Write-MailLog "Mail '$($Result.Subject)' to $($Result.To) not sent: $Why" -LogType WARNING
        if ($ThrowOnError) { throw "Send-ScriptMail: $Why" }
        [pscustomobject]$Result
    }

    #region Settings
    $Mail = $null
    try {
        $GetSettingsPath = Join-Path -Path $PSScriptRoot -ChildPath 'Get-ApplicationSettings.ps1'
        if (Test-Path -Path $GetSettingsPath) { . $GetSettingsPath; $Cfg = Get-ApplicationSettings -Path $SettingsPath }
        else { $Cfg = Get-Content -Path $SettingsPath -Raw | ConvertFrom-Json }
        if ($Cfg.PSObject.Properties['Mail']) { $Mail = $Cfg.Mail }
    }
    catch { return (Stop-Send "cannot read ${SettingsPath}: $($_.Exception.Message)") }
    $Get = { param($Name, $Default) if ($Mail -and $Mail.PSObject.Properties[$Name] -and $null -ne $Mail.$Name -and "$($Mail.$Name)" -ne '') { $Mail.$Name } else { $Default } }

    $Servers  = @(& $Get 'SmtpServers' @()) | Where-Object { $_ }
    $Port     = [int](& $Get 'Port' 25)
    $UseSsl   = [bool](& $Get 'UseSsl' $false)
    $Timeout  = [int](& $Get 'TimeoutSeconds' 30)
    $Prefix   = "$(& $Get 'SubjectPrefix' '')"
    $Pickup   = "$(& $Get 'PickupDirectory' '')"
    if (-not $From) { $From = "$(& $Get 'From' '')" }
    if (-not $To) { $To = @(& $Get 'To' @()) | Where-Object { $_ } }

    $FullSubject = (@($Prefix, $(if ($Application) { "$Application -" } else { '' }), $Subject) | Where-Object { $_ }) -join ' '
    $Result.Subject = $FullSubject
    $Result.To = (@($To) -join ', ')

    if (-not $Mail) { return (Stop-Send "no Mail section in $SettingsPath") }
    if ($Mail.PSObject.Properties['Enabled'] -and -not [bool]$Mail.Enabled) { return (Stop-Send 'mail is disabled (Mail.Enabled = false)') }
    if (-not $From) { return (Stop-Send 'no sender (Mail.From or -From)') }
    if (-not @($To).Count) { return (Stop-Send 'no recipients (Mail.To or -To)') }
    if (-not $Pickup -and -not $Servers.Count) { return (Stop-Send 'no SMTP server (Mail.SmtpServers)') }
    foreach ($A in @($Attachments | Where-Object { $_ })) {
        if (-not (Test-Path -LiteralPath $A -PathType Leaf)) { return (Stop-Send "attachment not found: $A") }
    }
    #endregion

    #region Message
    if (-not $NoFooter) {
        $Who = (@($(if ($Application) { $Application }), "$env:COMPUTERNAME") | Where-Object { $_ }) -join ' on '
        $Stamp = Get-Date -Format 'yyyy-MM-dd HH:mm:ss'
        $Body = if ($BodyAsHtml) { "$Body<hr><p style=""font-size:smaller;color:gray"">Sent by $Who at $Stamp.</p>" }
                else { "$Body`r`n`r`n--`r`nSent by $Who at $Stamp." }
    }
    try {
        $Msg = New-Object System.Net.Mail.MailMessage
        $Msg.From = New-Object System.Net.Mail.MailAddress($From)
        foreach ($R in @($To)) { $Msg.To.Add($R) }
        foreach ($R in @($Cc | Where-Object { $_ })) { $Msg.CC.Add($R) }
        foreach ($R in @($Bcc | Where-Object { $_ })) { $Msg.Bcc.Add($R) }
        $Msg.Subject = $FullSubject
        $Msg.Body = $Body
        $Msg.IsBodyHtml = [bool]$BodyAsHtml
        $Msg.BodyEncoding = [System.Text.Encoding]::UTF8
        $Msg.SubjectEncoding = [System.Text.Encoding]::UTF8
        $Msg.Priority = [System.Net.Mail.MailPriority]$Priority
        foreach ($A in @($Attachments | Where-Object { $_ })) { $Msg.Attachments.Add((New-Object System.Net.Mail.Attachment((Resolve-Path -LiteralPath $A).ProviderPath))) }
    }
    catch { return (Stop-Send "invalid message: $($_.Exception.Message)") }
    #endregion

    #region Send (each server in turn)
    if (-not $PSCmdlet.ShouldProcess("$($Result.To) via $(if ($Pickup) { $Pickup } else { $Servers -join ', ' })", "Send mail '$FullSubject'")) { $Msg.Dispose(); return }
    # Windows PowerShell 5.1 may not offer TLS 1.2 by default
    if ($UseSsl) { try { [System.Net.ServicePointManager]::SecurityProtocol = [System.Net.ServicePointManager]::SecurityProtocol -bor [System.Net.SecurityProtocolType]::Tls12 } catch { } }

    $Errors = @()
    $Targets = if ($Pickup) { @('(pickup)') } else { $Servers }
    try {
        foreach ($S in $Targets) {
            $Client = $null
            try {
                $Client = New-Object System.Net.Mail.SmtpClient
                if ($Pickup) {
                    if (-not (Test-Path -Path $Pickup)) { New-Item -ItemType Directory -Path $Pickup -Force | Out-Null }
                    $Client.DeliveryMethod = [System.Net.Mail.SmtpDeliveryMethod]::SpecifiedPickupDirectory
                    $Client.PickupDirectoryLocation = (Resolve-Path -Path $Pickup).ProviderPath
                }
                else {
                    $Client.Host = $S
                    $Client.Port = $Port
                    $Client.EnableSsl = $UseSsl
                    $Client.Timeout = $Timeout * 1000
                    $Client.UseDefaultCredentials = $false
                }
                $Client.Send($Msg)
                $Result.Sent = $true
                $Result.Server = if ($Pickup) { $Pickup } else { $S }
                $Result.Message = 'OK'
                Write-MailLog "Mail '$FullSubject' sent to $($Result.To) via $($Result.Server)$(if ($Errors) { " (after: $($Errors -join '; '))" })."
                break
            }
            catch {
                $E = $_.Exception
                while ($E.InnerException) { $E = $E.InnerException }
                $Errors += "${S}: $($E.Message)"
            }
            finally { if ($Client) { $Client.Dispose() } }
        }
    }
    finally { $Msg.Dispose() }
    #endregion

    if (-not $Result.Sent) { return (Stop-Send ($Errors -join '; ')) }
    [pscustomobject]$Result
}

