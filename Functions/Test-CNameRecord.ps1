<#
.SYNOPSIS
    Checks if a CNAME DNS record exists for a given name.
.DESCRIPTION
    This function queries DNS to determine if a specified CNAME record exists. Returns $true if found, otherwise $false.
.PARAMETER CName
    The DNS CNAME record to check (e.g., 'alias.example.com').
.PARAMETER DnsServer
    Optional. The DNS server to query. If not specified, the system default is used.
.EXAMPLE
    PS> Test-CNameRecord -CName "alias.example.com"
.INPUTS
    System.String
.OUTPUTS
    System.Boolean
.NOTES
    Author: Powershell Scripts Management
    Date: 2026-04-28
    Version: 1.0
    IsAIUsed: True
    AIUsed: GitHub Copilot
    ScriptType: Function
    Company: [YourCompany]
    License: MIT
    URLToLicense: https://opensource.org/licenses/MIT
.LINK
    https://docs.microsoft.com/en-us/powershell/module/dnsclient/resolve-dnsname
#>
function Test-CNameRecord {
    [CmdletBinding()]
    param (
        [Parameter(Mandatory = $true)]
        [string]$CName,
        [Parameter(Mandatory = $false)]
        [string]$DnsServer
    )
    try {
        $params = @{ Name = $CName; Type = 'CNAME' }
        if ($DnsServer) { $params['Server'] = $DnsServer }
        $result = Resolve-DnsName @params -ErrorAction Stop
        if ($result) {
            Write-Verbose "CNAME record '$CName' exists."
            return $true
        }
    } catch {
        Write-Verbose "CNAME record '$CName' does not exist or could not be resolved."
        return $false
    }
}

