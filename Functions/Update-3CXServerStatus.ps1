<#
.SYNOPSIS
    Updates the status and last checked time for a 3CX server in the 3CXStatus.json file.
.DESCRIPTION
    This function updates the status (e.g., 'Online', 'Offline', 'Unknown') and the last checked timestamp for either the PrimaryServer or FailoverServer in the 3CXStatus.json file.
.PARAMETER ServerType
    The server to update: 'PrimaryServer' or 'FailoverServer'.
.PARAMETER Status
    The new status to set (e.g., 'Online', 'Offline', 'Unknown').
.PARAMETER StatusFilePath
    Optional. The path to the 3CXStatus.json file. Defaults to the standard location.
.EXAMPLE
    PS> Update-3CXServerStatus -ServerType PrimaryServer -Status Online
.INPUTS
    System.String
.OUTPUTS
    None
.NOTES
    Author: Powershell Scripts Management
    Date: 2026-04-28
    Version: 1.0
    IsAIUsed: True
    AIUsed: GitHub Copilot
    ScriptType: Function
    Company: [YourCompany]
    License: MIT
    URLToLicense: https://opensource.org/licenses/MIT
.LINK
    https://docs.microsoft.com/en-us/powershell/module/microsoft.powershell.utility/convertto-json
#>
function Set-3CXServerStatus {
    [CmdletBinding()]
    param (
        [Parameter(Mandatory)]
        [ValidateSet('PrimaryServer','FailoverServer')]
        [string]$ServerType,
        [Parameter(Mandatory)]
        [string]$Status,
        [Parameter()]
        [string]$StatusFilePath = "c:\\SCRIPTS\\Applications\\3CX\\Failover3CXServer\\Data\\3CXStatus.json"
    )
    try {
        if (-not (Test-Path $StatusFilePath)) {
            $default = @{
                PrimaryServer = @{ Name = ""; Status = "Unknown"; LastChecked = $null };
                FailoverServer = @{ Name = ""; Status = "Unknown"; LastChecked = $null }
            }
            $default | ConvertTo-Json -Depth 3 | Set-Content $StatusFilePath
            Write-Verbose "Created new status file at $StatusFilePath."
        }
        $statusData = Get-Content $StatusFilePath | ConvertFrom-Json
        $statusData.$ServerType.Status = $Status
        $statusData.$ServerType.LastChecked = (Get-Date).ToString('yyyy-MM-ddTHH:mm:ss')
        $statusData | ConvertTo-Json -Depth 3 | Set-Content $StatusFilePath
        Write-Verbose "Set $ServerType status to '$Status' in $StatusFilePath."
    } catch {
        Write-Warning "Failed to set $ServerType status: $_"
    }
}

