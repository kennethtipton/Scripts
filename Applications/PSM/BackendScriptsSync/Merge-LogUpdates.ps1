[CmdletBinding(SupportsShouldProcess = $true)]
param(
    [string]$SettingsPath,
    [string]$DfsRoot
)

$ErrorActionPreference = 'Stop'
$ScriptName = 'Merge-LogUpdates.ps1'

#region Standard locations
$SCA = $PSScriptRoot
$SA  = $SCA
while ($SA -and (Split-Path -Path $SA -Leaf) -ne 'Applications') { $SA = Split-Path -Path $SA -Parent }
if (-not $SA) { throw "$SCA is not inside an 'Applications' folder." }
$SL = Split-Path -Path $SA -Parent
$SF = Join-Path -Path $SL -ChildPath 'Functions'
if (-not $SettingsPath) { $SettingsPath = Join-Path -Path $SL -ChildPath 'Data\Settings\Scripts.json' }
#endregion

foreach ($F in 'Write-AdvancedLog.ps1', 'Get-ApplicationSettings.ps1', 'Get-ScriptsTransport.ps1') {
    $P = Join-Path -Path $SF -ChildPath $F
    if (Test-Path -Path $P) { . $P }
}
function Write-MergeLog {
    param([Parameter(Mandatory)][string]$Message, [ValidateSet('INFO', 'WARNING', 'ERROR')][string]$LogType = 'INFO')
    if ($LogType -eq 'INFO') { Write-Verbose $Message; return }
    Write-Warning $Message
    if (-not $WhatIfPreference -and (Get-Command -Name Write-AdvancedLog -ErrorAction SilentlyContinue)) {
        try { Write-AdvancedLog -Message $Message -ScriptName $ScriptName -LogFileName 'Merge-LogUpdates' -LogType $LogType -WriteEventLog } catch { }
    }
}

$Summary = [pscustomobject]@{ Files = 0; Records = 0; Rejected = 0; Purged = 0; Failed = 0; Messages = New-Object System.Collections.Generic.List[string] }
$Utf8 = New-Object System.Text.UTF8Encoding($false)
$Columns = 'Time', 'Server', 'Script', 'Type', 'Message'

# Text for one CSV field: quoted, quotes doubled
function ConvertTo-CsvField { param($Value) '"' + ("$Value" -replace '"', '""') + '"' }

try {
    #region Settings
    $Cfg = if (Get-Command -Name Get-ApplicationSettings -ErrorAction SilentlyContinue) { Get-ApplicationSettings -Path $SettingsPath } else { Get-Content -Path $SettingsPath -Raw | ConvertFrom-Json }
    $S = $Cfg.LogShipping
    $Get = { param($Name, $Default) if ($S -and $S.PSObject.Properties[$Name] -and "$($S.$Name)" -ne '') { $S.$Name } else { $Default } }
    $RetentionDays = [int](& $Get 'RetentionDays' 90)
    $KeepIngested  = [int](& $Get 'IngestedKeepDays' 7)
    if (-not $DfsRoot) {
        $DfsRoot = "$((Get-ScriptsTransport -Settings $Cfg -Type Dfs | Select-Object -First 1).Root)"
        if (-not $DfsRoot) { throw 'No Dfs transport in the settings.' }
    }
    $DfsRoot  = $DfsRoot.TrimEnd('\')
    $Updates  = Join-Path -Path $DfsRoot -ChildPath "$(& $Get 'UpdatesFolder' 'Logs\Updates')"
    $Central  = Join-Path -Path $DfsRoot -ChildPath "$(& $Get 'CentralFolder' 'Logs\Central')"
    $Ingested = Join-Path -Path $Updates -ChildPath '_Ingested'
    $Rejected = Join-Path -Path $Updates -ChildPath '_Rejected'
    if (-not (Test-Path -Path $Updates -PathType Container)) { Write-Verbose "$Updates does not exist yet: no device has sent logs."; return $Summary }
    #endregion

    #region Merge
    $Drops = @(Get-ChildItem -Path $Updates -Directory | Where-Object { $_.Name -notlike '_*' } |
        ForEach-Object { Get-ChildItem -Path $_.FullName -Filter '*.jsonl' -File } | Sort-Object LastWriteTime, Name)
    $Today = Get-Date
    foreach ($D in $Drops) {
        $Device = $D.Directory.Name
        $Summary.Files++
        try {
            $Recs = @(foreach ($Line in [System.IO.File]::ReadAllLines($D.FullName, [System.Text.Encoding]::UTF8)) {
                if ($Line.Trim()) { $Line | ConvertFrom-Json }
            })
        }
        catch {
            $Summary.Rejected++
            $Summary.Messages.Add("$Device\$($D.Name): $($_.Exception.Message)")
            Write-MergeLog "Rejected $Device\$($D.Name) (unreadable): $($_.Exception.Message)" -LogType WARNING
            if ($PSCmdlet.ShouldProcess($D.FullName, 'Move to _Rejected')) {
                $To = Join-Path -Path $Rejected -ChildPath $Device
                if (-not (Test-Path $To)) { New-Item -ItemType Directory -Path $To -Force | Out-Null }
                Move-Item -LiteralPath $D.FullName -Destination (Join-Path $To $D.Name) -Force
            }
            continue
        }

        try {
            # Group by target file: <Log>\<yyyy-MM>\<Log>_<yyyy-MM-dd>.csv
            $Groups = @{}
            foreach ($R in $Recs) {
                $Log = if ("$($R.Log)") { ("$($R.Log)" -replace '[\\/:*?"<>|]', '_') } else { 'Unknown' }
                $Day = $Today
                if ("$($R.Time)") { try { $Day = ([DateTimeOffset]::Parse("$($R.Time)", [Globalization.CultureInfo]::InvariantCulture)).DateTime } catch { } }
                $Path = Join-Path -Path $Central -ChildPath ('{0}\{1:yyyy-MM}\{0}_{1:yyyy-MM-dd}.csv' -f $Log, $Day)
                if (-not $Groups.ContainsKey($Path)) { $Groups[$Path] = New-Object System.Collections.Generic.List[string] }
                $Server = if ("$($R.Server)") { "$($R.Server)" } else { $Device }
                $Groups[$Path].Add((@("$($R.Time)", $Server, "$($R.Script)", "$($R.Type)", "$($R.Message)") | ForEach-Object { ConvertTo-CsvField $_ }) -join ',')
            }
            if ($PSCmdlet.ShouldProcess("$Device\$($D.Name)", "Merge $($Recs.Count) record(s) into $($Groups.Count) central file(s)")) {
                foreach ($Path in $Groups.Keys) {
                    $Dir = Split-Path -Path $Path -Parent
                    if (-not (Test-Path $Dir)) { New-Item -ItemType Directory -Path $Dir -Force | Out-Null }
                    $Text = ($Groups[$Path] -join "`r`n") + "`r`n"
                    if (-not (Test-Path -LiteralPath $Path)) { $Text = (($Columns | ForEach-Object { ConvertTo-CsvField $_ }) -join ',') + "`r`n" + $Text }
                    [System.IO.File]::AppendAllText($Path, $Text, $Utf8)
                }
                $To = Join-Path -Path $Ingested -ChildPath ('{0:yyyyMMdd}\{1}' -f $Today, $Device)
                if (-not (Test-Path $To)) { New-Item -ItemType Directory -Path $To -Force | Out-Null }
                Move-Item -LiteralPath $D.FullName -Destination (Join-Path $To $D.Name) -Force
            }
            $Summary.Records += $Recs.Count
        }
        catch {
            $Summary.Failed++
            $Summary.Messages.Add("$Device\$($D.Name): $($_.Exception.Message)")
            Write-MergeLog "Could not merge $Device\$($D.Name): $($_.Exception.Message)" -LogType ERROR
        }
    }
    #endregion

    #region Retention
    if (Test-Path -Path $Central) {
        $Cut = $Today.Date.AddDays(-$RetentionDays)
        foreach ($Old in @(Get-ChildItem -Path $Central -Filter '*.csv' -File -Recurse | Where-Object { $_.BaseName -match '_(\d{4}-\d{2}-\d{2})$' -and [datetime]$Matches[1] -lt $Cut })) {
            if ($PSCmdlet.ShouldProcess($Old.FullName, "Delete (older than $RetentionDays days)")) { Remove-Item -LiteralPath $Old.FullName -Force; $Summary.Purged++ }
        }
        Get-ChildItem -Path $Central -Directory -Recurse | Sort-Object { $_.FullName.Length } -Descending |
            Where-Object { -not (Get-ChildItem -LiteralPath $_.FullName -Force) } |
            ForEach-Object { if ($PSCmdlet.ShouldProcess($_.FullName, 'Remove empty folder')) { Remove-Item -LiteralPath $_.FullName -Force } }
    }
    if (Test-Path -Path $Ingested) {
        Get-ChildItem -Path $Ingested -Directory | Where-Object { $_.Name -match '^\d{8}$' -and [datetime]::ParseExact($_.Name, 'yyyyMMdd', $null) -lt $Today.Date.AddDays(-$KeepIngested) } |
            ForEach-Object { if ($PSCmdlet.ShouldProcess($_.FullName, 'Delete ingested updates')) { Remove-Item -LiteralPath $_.FullName -Recurse -Force } }
    }
    #endregion

    Write-Verbose ('Merged {0} update file(s), {1} record(s) into {2}; {3} rejected, {4} failed, {5} old day file(s) purged.' -f $Summary.Files, $Summary.Records, $Central, $Summary.Rejected, $Summary.Failed, $Summary.Purged)
}
catch {
    $Summary.Failed++
    $Summary.Messages.Add($_.Exception.Message)
    Write-MergeLog "Log merge failed: $($_.Exception.Message)" -LogType ERROR
}
$Summary

