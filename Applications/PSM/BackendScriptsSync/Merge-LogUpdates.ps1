<#
.SYNOPSIS
    Merges the log lines the devices sent to DFS (Logs\Updates\<DEVICE>\*.jsonl) into the central log
    store: one CSV per log per day, with a Server column.
.DESCRIPTION
    Part of Powershell Scripts Management (PSM), Backend. Runs at the end of every
    Update-InventoryIndex.ps1 run (task \PSM\UpdateInventoryIndex on the InventoryServer), or on its own.

      1. Reads every update file in <DfsRoot>\Logs\Updates\<DEVICE>\ (oldest first; *.tmp are
         still being written and are skipped). Send-LogsToDfs.ps1 on each device writes them.
      2. Appends the records to <DfsRoot>\Logs\Central\<Log>\<yyyy-MM>\<Log>_<yyyy-MM-dd>.csv
         (columns Time, Server, Script, Type, Message; UTF-8). The day is the record's own date.
         Records without a time go to the day the file was merged.
      3. Moves each merged update file to Logs\Updates\_Ingested\<yyyyMMdd>\<DEVICE>\ (kept
         IngestedKeepDays, then deleted). A file that cannot be read is moved to
         Logs\Updates\_Rejected\ and reported.
      4. Deletes central day files older than RetentionDays (and empty month folders).

    Writes its own log only for warnings and errors: its log is shipped and merged too, so an INFO
    line per run would come back every run.

    Settings: LogShipping in C:\SCRIPTS\Data\Settings\Scripts.json (UpdatesFolder, CentralFolder,
    RetentionDays, IngestedKeepDays). Needs Modify on <DfsRoot>\Logs\Updates (FLD-SCRIPTS.Logs.Updates.EDITORS,
    as a Frontend) and <DfsRoot>\Logs\Central (FLD-SCRIPTS.Logs.Central.EDITORS, through APP-PowershellScriptsManagement.Backend).
.PARAMETER SettingsPath
    Settings file. Defaults to C:\SCRIPTS\Data\Settings\Scripts.json.
.PARAMETER DfsRoot
    DFS scripts root. Defaults to the Dfs transport's Root in the settings.
.EXAMPLE
    PS> C:\SCRIPTS\Applications\PSM\BackendScriptsSync\Merge-LogUpdates.ps1 -Verbose
.INPUTS
