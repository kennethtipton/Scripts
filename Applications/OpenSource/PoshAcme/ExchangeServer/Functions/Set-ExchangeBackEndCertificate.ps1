<#
.SYNOPSIS
    Binds a certificate to the Exchange Back End IIS site (https :444).
.DESCRIPTION
    Finds the https binding on the 'Exchange Back End' site and assigns the given certificate
    from LocalMachine\My if it is not already assigned. Returns an object describing the
    previous and current thumbprints and whether anything changed.
    Exchange's own cmdlets (Enable-ExchangeCertificate -Services IIS) only update the front end
    (Default Web Site :443), so this is needed after every certificate change.
.PARAMETER Thumbprint
    Thumbprint of the certificate in LocalMachine\My to bind.
.PARAMETER SiteName
    IIS site name. Defaults to 'Exchange Back End'.
.PARAMETER Port
    https port of the binding. Defaults to 444.
.EXAMPLE
    PS> Set-ExchangeBackEndCertificate -Thumbprint 9235D06E3B6AA931E49E9B811F609FF55D7C545C
.EXAMPLE
    PS> Set-ExchangeBackEndCertificate -Thumbprint 9235D06E3B6AA931E49E9B811F609FF55D7C545C -WhatIf
