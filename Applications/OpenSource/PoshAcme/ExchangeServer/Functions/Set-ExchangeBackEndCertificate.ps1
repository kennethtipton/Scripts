function Set-ExchangeBackEndCertificate {
    [CmdletBinding(SupportsShouldProcess = $true)]
    [OutputType([pscustomobject])]
    param(
        [Parameter(Mandatory = $true)]
        [ValidatePattern('^[0-9A-Fa-f]{40}$')]
        [string]$Thumbprint,

        [Parameter(Mandatory = $false)]
        [string]$SiteName = 'Exchange Back End',

        [Parameter(Mandatory = $false)]
        [int]$Port = 444
    )

    Import-Module WebAdministration -ErrorAction Stop
    $Thumb = $Thumbprint.ToUpper()

    if (-not (Test-Path -Path "Cert:\LocalMachine\My\$Thumb")) {
        throw "Certificate $Thumb was not found in LocalMachine\My."
    }

    $Binding = Get-WebBinding -Name $SiteName -Protocol https -Port $Port | Select-Object -First 1
    if (-not $Binding) {
        throw "No https:$Port binding found on the '$SiteName' site."
    }

    $Previous = "$($Binding.certificateHash)".ToUpper()
    $Changed  = $false

    if ($Previous -ne $Thumb) {
        if ($PSCmdlet.ShouldProcess("$SiteName :$Port", "Bind certificate $Thumb (was '$Previous')")) {
            $Binding.AddSslCertificate($Thumb, 'My')
            $Changed = $true
        }
    }

    [pscustomobject]@{
        Site               = $SiteName
        Port               = $Port
        PreviousThumbprint = $Previous
        Thumbprint         = $Thumb
        Changed            = $Changed
    }
}

