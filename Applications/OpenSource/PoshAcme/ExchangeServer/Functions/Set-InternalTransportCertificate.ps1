function Set-InternalTransportCertificate {
    [CmdletBinding(SupportsShouldProcess = $true)]
    [OutputType([pscustomobject])]
    param(
        [Parameter(Mandatory = $true)]
        [ValidatePattern('^[0-9A-Fa-f]{40}$')]
        [string]$Thumbprint,

        [Parameter(Mandatory = $false)]
        [string]$Server = $env:COMPUTERNAME
    )

    if (-not (Get-Command -Name Get-TransportService -ErrorAction SilentlyContinue)) {
        Add-PSSnapin Microsoft.Exchange.Management.PowerShell.SnapIn -ErrorAction Stop
    }

    $Thumb    = $Thumbprint.ToUpper()
    $Previous = "$((Get-TransportService -Identity $Server -ErrorAction Stop).InternalTransportCertificateThumbprint)".ToUpper()
    $Changed  = $false

    if ($Previous -ne $Thumb) {
        $Cert = Get-ExchangeCertificate -Server $Server -Thumbprint $Thumb -ErrorAction SilentlyContinue
        if (-not $Cert) {
            throw "Certificate $Thumb is not installed on $Server. Internal transport left as '$Previous'."
        }

        if ($PSCmdlet.ShouldProcess($Server, "Set internal transport certificate to $Thumb (was '$Previous')")) {
            Enable-ExchangeCertificate -Server $Server -Thumbprint $Thumb -Services SMTP -Force -ErrorAction Stop
            $Changed = $true
        }
    }

    [pscustomobject]@{
        Server             = $Server
        PreviousThumbprint = $Previous
        Thumbprint         = $Thumb
        Changed            = $Changed
    }
}

