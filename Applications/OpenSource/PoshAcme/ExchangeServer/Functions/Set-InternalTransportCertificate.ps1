<#
.SYNOPSIS
    Sets the default internal transport (SMTP) certificate on an Exchange server.
.DESCRIPTION
    Compares the server's InternalTransportCertificateThumbprint with the requested certificate
    and, if they differ, makes the requested certificate the default SMTP certificate with
    Enable-ExchangeCertificate -Services SMTP -Force.
    Posh-ACME.Deploy's Set-ExchangeCertificate takes this role for the Let's Encrypt certificate
    on every renewal, and LE certificates rotate every ~60 days, so this pins it back to a
    stable certificate. Loads the Exchange snap-in if the Exchange cmdlets are not available.
.PARAMETER Thumbprint
    Thumbprint of the certificate to use for internal transport. It must already be installed
    on the server.
.PARAMETER Server
    Exchange server to configure. Defaults to the local computer.
.EXAMPLE
    PS> Set-InternalTransportCertificate -Thumbprint B1E5BFBCC966D2D0F563D18B0E91CDCBC8D7C1F6
.EXAMPLE
    PS> Set-InternalTransportCertificate -Thumbprint B1E5BFBCC966D2D0F563D18B0E91CDCBC8D7C1F6 -Server srv010010050050 -WhatIf
.INPUTS
    [string] Thumbprint, [string] Server
.OUTPUTS
